// 欠阻尼弹簧：0 → 1（扫描“咔”地对齐时冲过头一点再回来）
const spring = (sec, freq = 2.2, zeta = 0.35) => {
  if (sec <= 0) return 0; const w = 2 * Math.PI * freq, wd = w * Math.sqrt(1 - zeta * zeta);
  return 1 - Math.exp(-zeta * w * sec) * (Math.cos(wd * sec) + zeta * w / wd * Math.sin(wd * sec));
};
