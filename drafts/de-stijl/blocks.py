"""风格派的核心工具：只用横竖两种矩形拼字、切画面。

字母按 Van Doesburg（1919）/ Huszár（1917《De Stijl》刊头）的做法：每一笔是一根矩形，
笔与笔相接处留一道缝，字是“搭”出来的，不是“写”出来的。单位 u = 笔画宽。
"""
PAPER, INK, RED, YEL, BLUE = '#F3F0E8', '#121212', '#D52B1E', '#F4C51C', '#1C4DA1'
GAP = 0.25
G = 1 + GAP
LETTERS = {  # (x, y, w, h)，字框 5×7
    'D': [(0, 0, 1, 7), (G, 0, 2.5, 1), (G, 6, 2.5, 1), (4, G, 1, 7 - 2 * G)],
    'E': [(0, 0, 1, 7), (G, 0, 5 - G, 1), (G, 3, 3.6 - G, 1), (G, 6, 5 - G, 1)],
    'S': [(0, 0, 5, 1), (0, G, 1, 3 - G - GAP), (0, 3, 5, 1), (4, 3 + G, 1, 3 - G - GAP), (0, 6, 5, 1)],
    'T': [(0, 0, 5, 1), (2, G, 1, 7 - G)],
    'I': [(0, 0, 1, 7)],
    'J': [(4, 0, 1, 6 - GAP), (0, 6, 5, 1), (0, 4.5, 1, 1.5 - GAP)],
    'L': [(0, 0, 1, 6 - GAP), (0, 6, 5, 1)],
    'O': [(0, 0, 5, 1), (0, 6, 5, 1), (0, G, 1, 7 - 2 * G), (4, G, 1, 7 - 2 * G)],
    'R': [(0, 0, 1, 7), (G, 0, 3.75 - GAP, 1), (4, 0, 1, 3 - GAP), (G, 3, 3.75 - GAP, 1), (4, 3 + G, 1, 3 - G)],
    'N': [(0, 0, 1, 7), (G, 0, 2.75 - GAP, 1), (4, 0, 1, 7)],
    'G': [(0, 0, 5, 1), (0, G, 1, 7 - 2 * G), (0, 6, 5, 1), (4, 3, 1, 3 - GAP), (2.5, 3, 1.5 - GAP, 1)],
    'A': [(0, 0, 5, 1), (0, G, 1, 7 - G), (4, G, 1, 7 - G), (G, 3.5, 3 - 2 * GAP, 1)],
    'M': [(0, 0, 1, 7), (G, 0, 2.75, 1), (2, G, 1, 2.75), (4, 0, 1, 7)],
    'U': [(0, 0, 1, 6 - GAP), (4, 0, 1, 6 - GAP), (0, 6, 5, 1)],
    'C': [(0, 0, 5, 1), (0, G, 1, 7 - 2 * G), (0, 6, 5, 1)],
    'B': [(0, 0, 1, 7), (G, 0, 3.5, 1), (G, 3, 3.5, 1), (G, 6, 3.75 - GAP, 1), (4, 3 + G, 1, 3 - G - GAP)],
}
WIDTH = {'I': 1, 'T': 5}


def word(text, u, x0, y0, colors=None, track=1.2):
    """返回 [(x, y, w, h, 颜色)]。colors: {(字序号, 笔序号): 颜色}"""
    out, x = [], x0
    for i, ch in enumerate(text):
        if ch == ' ':
            x += 2.2 * u
            continue
        for j, (a, b, w, h) in enumerate(LETTERS[ch]):
            c = (colors or {}).get((i, j), INK)
            out.append((x + a * u, y0 + b * u, w * u, h * u, c))
        x += (WIDTH.get(ch, 5) + track) * u
    return out, x - track * u - x0


def rects_svg(rs):
    return ''.join(f'<rect x="{x:.1f}" y="{y:.1f}" width="{w:.1f}" height="{h:.1f}" fill="{c}"/>' for x, y, w, h, c in rs)
