"""等距微缩房间：一间剖开的小屋子，所有家具都是低多边形的盒子和二十面体。build(S, t) 往场景里放东西。"""
import math


def build(S, falling=True, night=True):
    WOOD, WALL1, WALL2 = '#C48A5A', '#EADCC8', '#DDCDB8'
    S.layer = 0
    S.box(0, -0.6, 0, 12, 12, 0.6, WOOD, top='#D49A68')                     # 地板
    for i in range(1, 12, 2):                                                 # 地板缝
        S.box(i, 0.0, 0, 0.04, 12, 0.01, '#B67C4E')
    S.box(-0.5, -0.6, -0.5, 0.5, 12.5, 9, WALL1)                              # 左墙（x=0）
    S.box(0, -0.6, -0.5, 12, 0.5, 9, WALL2)                                   # 右墙（z=0）
    S.box(-0.5, 8.4, -0.5, 0.5, 12.5, 0.2, '#C9B79F'); S.box(0, 8.4, -0.5, 12, 0.5, 0.2, '#C9B79F')
    # 窗（左墙）：夜色 + 月亮
    S.layer = 1
    S.box(0, 3.0, 6.4, 0.06, 4.4, 3.4, '#4B3FA8' if night else '#9FD6FF', emit=0.9)
    S.box(0.06, 4.6, 6.4, 0.08, 4.4, 0.18, '#F4EEE6'); S.box(0.06, 3.0, 8.5, 0.08, 0.18, 3.4, '#F4EEE6')
    S.box(0.02, 5.6, 9.6, 0.05, 0.7, 0.7, '#FFF4C8', emit=1.0)
    S.box(0.1, 2.85, 6.2, 0.6, 4.8, 0.18, '#F4EEE6')                          # 窗台
    S.layer = 0
    # 地毯
    S.layer = 1
    S.box(3.2, 0, 3.6, 5.6, 5.2, 0.06, '#E2725B', top='#E8826B')
    S.box(3.6, 0.06, 4.0, 4.8, 4.4, 0.01, '#F2B880')
    # 床（右墙边）
    S.layer = 2
    S.box(6.4, 0, 0.2, 5.4, 3.4, 1.0, '#8C6A4F')
    S.box(6.5, 1.0, 0.3, 5.2, 3.2, 0.55, '#F7F2EA')
    S.box(8.6, 1.55, 0.25, 3.25, 3.3, 0.18, '#5B7BD9', top='#6E8DE6')
    S.box(6.7, 1.55, 0.6, 1.5, 2.5, 0.45, '#FFFFFF')
    S.box(6.4, 1.0, 0.0, 5.4, 0.25, 2.6, '#7A5A42')                           # 床头板
    # 书桌 + 显示器 + 椅子（左墙边）
    S.box(0.1, 2.6, 0.8, 2.8, 4.6, 0.22, '#B98558')
    for lx, lz in [(0.3, 1.0), (2.6, 1.0), (0.3, 5.1), (2.6, 5.1)]:
        S.box(lx, 0, lz, 0.18, 0.18, 2.6, '#7A5A42')
    S.box(0.35, 2.82, 2.0, 0.3, 2.4, 1.6, '#2B2B36')
    S.box(0.66, 2.95, 2.12, 0.03, 2.16, 1.36, '#7FD8FF', emit=0.95)
    S.box(1.6, 2.82, 4.2, 0.9, 0.6, 0.5, '#E07A5F')                           # 马克杯
    S.box(3.1, 0, 2.6, 1.5, 1.5, 1.5, '#F2B13A', top='#F6C25A')
    S.box(4.4, 1.5, 2.6, 0.25, 1.5, 1.8, '#F2B13A')
    # 墙上书架
    S.box(2.0, 5.4, 0.0, 3.6, 1.1, 0.2, '#9C7452')
    for i, c in enumerate(['#E24A3B', '#3D7BD9', '#F2B13A', '#4FA36A', '#8E5BD6', '#E07A5F']):
        S.box(2.2 + i * 0.5, 5.6, 0.1, 0.4, 0.8, 1.1 + (i % 3) * 0.2, c)
    # 植物
    S.box(0.6, 0, 10.6, 1.2, 1.2, 1.1, '#E07A5F')
    for k, (dx, dy, dz, r) in enumerate([(0, 2.0, 0, 0.9), (-0.4, 2.8, 0.3, 0.7), (0.4, 2.6, -0.3, 0.75), (0.1, 3.4, 0.1, 0.55)]):
        S.ico(1.2 + dx, dy - 0.2, 11.2 + dz, r, ['#3E9B5B', '#4FAE68', '#36884F', '#5BBE74'][k], seed=k, jitter=0.2)
    # 落地灯
    S.box(5.0, 0, 0.6, 0.9, 0.9, 0.15, '#3A3440'); S.box(5.38, 0.15, 0.98, 0.14, 0.14, 4.6, '#3A3440')
    S.cone(5.45, 4.4, 1.05, 0.9, 1.1, '#FFD27A', n=8)
    S.box(5.15, 4.25, 0.75, 0.6, 0.6, 0.3, '#FFF1C2', emit=1.0)
    # 猫（橘）
    S.box(5.0, 0.07, 5.6, 1.6, 0.9, 0.8, '#F08A3A'); S.box(6.4, 0.5, 5.65, 0.8, 0.8, 0.75, '#F08A3A')
    S.cone(6.6, 1.25, 5.8, 0.18, 0.35, '#E07A2E', n=4); S.cone(7.0, 1.25, 6.25, 0.18, 0.35, '#E07A2E', n=4)
    S.box(4.4, 0.3, 6.0, 0.9, 0.2, 0.2, '#F08A3A')
    if falling:  # 豆袋沙发正落下来、海报正往墙上贴
        S.ico(5.5, 4.4, 8.6, 1.3, '#8E5BD6', seed=7, sy=0.75, jitter=0.15)
        S.box(-0.0, 4.2, 1.2, 0.08, 1.8, 2.4, '#F2B13A')
        S.box(0.08, 4.5, 1.5, 0.02, 1.2, 1.8, '#E24A3B')
