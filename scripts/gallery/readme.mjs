import {mkdir, readFile, writeFile} from 'node:fs/promises';
import path from 'node:path';
import {root, loadCatalog, coverSource} from './catalog.mjs';
import {escapeHtml, isOverview, selectWorks} from '../../gallery/assets/model.mjs';

// The overview already contains a collage; use individual works for the banner.
const works = selectWorks((await loadCatalog()).filter(work => !isOverview(work)));
const mosaicPath = 'docs/assets/style-mosaic.svg';
const width = 1600;
// Balance the rows while keeping every cover at 16:9 and the banner compact.
const rowCount = Math.max(1, Math.round(Math.sqrt(works.length * 0.8)));
const images = [];
let index = 0;
let y = 0;
for (let row = 0; row < rowCount; row++) {
  const count = Math.ceil((works.length - index) / (rowCount - row));
  const tileWidth = width / count;
  const tileHeight = tileWidth * 9 / 16;
  for (let column = 0; column < count; column++) {
    const work = works[index++];
    const cover = await readFile(path.join(root, coverSource(work)));
    images.push(`  <image id="work-${work.id}" x="${column * tileWidth}" y="${y}" width="${tileWidth}" height="${tileHeight}" preserveAspectRatio="xMidYMid meet" href="data:image/jpeg;base64,${cover.toString('base64')}"><title>${escapeHtml(work.title)} · ${escapeHtml(work.titleEn)}</title></image>`);
  }
  y += tileHeight;
}
const mosaic = `<svg xmlns="http://www.w3.org/2000/svg" width="${width}" height="${y}" viewBox="0 0 ${width} ${y}">\n  <title>Design Style · ${works.length} works</title>\n${images.join('\n')}\n</svg>\n`;
await mkdir(path.dirname(path.join(root, mosaicPath)), {recursive: true});
await writeFile(path.join(root, mosaicPath), mosaic);

for (const language of ['zh','en']) {
  const begin = '<!-- BEGIN WORK PREVIEWS -->';
  const end = '<!-- END WORK PREVIEWS -->';
  const file = path.join(root, language === 'en' ? 'README.en.md' : 'README.md');
  const readme = await readFile(file, 'utf8');
  const start = readme.indexOf(begin);
  const finish = readme.indexOf(end);
  if (start < 0 || finish < start || readme.indexOf(begin, start + begin.length) !== -1 || readme.indexOf(end, finish + end.length) !== -1) {
    throw new Error('README 需要且只能有一组 WORK PREVIEWS 标记');
  }
  const note = language === 'en' ? 'Generated by npm run gallery:readme from gallery/data/works.json. Do not edit this block.' : '由 npm run gallery:readme 根据 gallery/data/works.json 生成，请勿手动修改此区域。';
  const alt = language === 'en' ? `A mosaic of ${works.length} work covers · Open the gallery` : `${works.length} 张作品封面拼图 · 点击进入画廊`;
  const previews = `${begin}\n<!-- ${note} -->\n<p><a href="https://guanmo-ai.github.io/design-style/?lang=${language}"><img src="${mosaicPath}" width="100%" alt="${alt}" /></a></p>\n${end}`;
  const updated = readme.slice(0, start) + previews + readme.slice(finish + end.length);
  if (updated !== readme) await writeFile(file, updated);
}
console.log(`中英文 README 拼图已同步：${works.length} 张作品封面，${rowCount} 行`);
